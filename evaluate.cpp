int evaluate(const Board &b)
{
    int score = 0;
    for (int sq = 0; sq < 128; sq++)
    {
        if (!is_on_board(sq))
            continue;

        int piece = b.squares[sq];
        if (piece == EMPTY)
            continue;

        int type = type_of(piece);
        int color = color_of(piece);

        int value = 0;
        switch (type)
        {
        case W_PAWN:
            value = PAWN_VALUE + PST_PAWN[sq];
            break;
        case W_KNIGHT:
            value = KNIGHT_VALUE + PST_KNIGHT[sq];
            break;
        case W_BISHOP:
            value = BISHOP_VALUE + PST_BISHOP[sq];
            break;
        case W_ROOK:
            value = ROOK_VALUE + PST_ROOK[sq];
            break;
        case W_QUEEN:
            value = QUEEN_VALUE + PST_QUEEN[sq];
            break;
        case W_KING:
            value = KING_VALUE + PST_KING[sq];
            break;
        default:
            break;
        }

        score += (color == 1) ? value : -value;
    }

    return score;
}